// what this catches: the ballpark-first sampler (common/sampling.cpp, coarse_cap; CONTINUUM-ENGINE 4.7.13)
// picks EXACTLY the token the full-vocabulary path picks, on a real model's logits, step after step:
// two samplers with the same parameters and seed, one eligible for the ballpark path and one forced onto
// the full path (n_probs = 1 makes it ineligible), sample every step of a long generation with penalties
// active and the window sliding; any difference fails. Prints each path's per-token time (alternating
// which goes first) and the ballpark path's counters (cap, reseeds, widens, mean candidates).
//
// usage: test-sampler-coarse -m <model.gguf>
#include "arg.h"
#include "common.h"
#include "sampling.h"
#include "llama.h"

#include <chrono>
#include <clocale>
#include <cstdio>
#include <vector>

int main(int argc, char ** argv) {
    std::setlocale(LC_NUMERIC, "C");
    common_params params;
    if (!common_params_parse(argc, argv, params, LLAMA_EXAMPLE_COMMON)) {
        return 1;
    }
    common_init();
    llama_backend_init();
    auto init = common_init_from_params(params);
    llama_model * model = init->model();
    llama_context * ctx = init->context();
    if (model == nullptr || ctx == nullptr) { std::fprintf(stderr, "FAILED: model did not load\n"); return 1; }

    const llama_vocab * vocab = llama_model_get_vocab(model);
    common_params_sampling base;
    base.temp = 0.8f; base.top_k = 40; base.top_p = 0.95f; base.min_p = 0.05f;
    base.penalty_last_n = 256; base.penalty_repeat = 1.1f; base.penalty_freq = 0.2f; base.penalty_present = 0.1f;
    base.seed = 1234;

    // one case: two samplers (ballpark-eligible, and the full-vocabulary reference), the same prompt, the
    // same seed; `clone_each_step` samples the ballpark side through a fresh clone (speculative verify);
    // `prefix_accept` is accepted as generated by both before sampling (e.g. an opened think block)
    auto run_case = [&](const char * name, common_params_sampling sp, bool clone_each_step, const std::string & prefix_accept) {
        llama_memory_seq_rm(llama_get_memory(ctx), 0, -1, -1);
        common_params_sampling sp_full = sp;
        sp_full.n_probs = 1; // ineligible for the ballpark path: the full-vocabulary reference
        common_sampler * coarse = common_sampler_init(model, sp);
        common_sampler * full   = common_sampler_init(model, sp_full);
        std::vector<llama_token> prompt = common_tokenize(vocab, "Write a long story about a lighthouse keeper who repeats himself." + prefix_accept, true, true);
        for (const auto t : common_tokenize(vocab, prefix_accept, false, true)) {
            common_sampler_accept(coarse, t, true);
            common_sampler_accept(full, t, true);
        }
        llama_batch batch = llama_batch_init(512, 0, 1);
        for (size_t i = 0; i < prompt.size(); ++i) common_batch_add(batch, prompt[i], (llama_pos) i, { 0 }, i + 1 == prompt.size());
        if (llama_decode(ctx, batch) != 0) { std::fprintf(stderr, "FAILED: %s: prompt decode\n", name); std::exit(1); }
        llama_pos pos = (llama_pos) prompt.size();
        const int steps = 400;
        double us_coarse = 0, us_full = 0;
        int done = 0;
        for (int s = 0; s < steps; ++s) {
            llama_synchronize(ctx);
            llama_token a, b;
            auto time = [&](common_sampler * smpl, double & acc, bool clone) {
                common_sampler * use = clone ? common_sampler_clone(smpl) : smpl;
                auto t0 = std::chrono::steady_clock::now();
                const llama_token id = common_sampler_sample(use, ctx, -1);
                acc += std::chrono::duration<double, std::micro>(std::chrono::steady_clock::now() - t0).count();
                if (clone) common_sampler_free(use);
                return id;
            };
            // both sides sample through a clone when cloning, so their random streams stay in step (a clone's
            // RNG advances, the original's does not: cloning one side only is a test asymmetry, not a check)
            if (s % 2 == 0) { a = time(coarse, us_coarse, clone_each_step); b = time(full, us_full, clone_each_step); }
            else            { b = time(full, us_full, clone_each_step); a = time(coarse, us_coarse, clone_each_step); }
            if (a != b) {
                std::fprintf(stderr, "FAILED: %s: step %d: ballpark picked %d, the full vocabulary picked %d\n", name, s, a, b);
                std::exit(1);
            }
            common_sampler_accept(coarse, a, true);
            common_sampler_accept(full, b, true);
            done++;
            if (llama_vocab_is_eog(vocab, a)) break;
            common_batch_clear(batch);
            common_batch_add(batch, a, pos++, { 0 }, true);
            if (llama_decode(ctx, batch) != 0) { std::fprintf(stderr, "FAILED: %s: decode\n", name); std::exit(1); }
        }
        size_t cap = 0; uint64_t calls = 0, reseeds = 0, widens = 0, cands = 0;
        common_sampler_coarse_stats(coarse, &cap, &calls, &reseeds, &widens, &cands);
        std::printf("%-18s identical over %3d steps; per token ballpark %.1f us, full %.1f us; cap %zu, ballpark calls %llu, widens %llu, mean candidates %.0f\n",
                    name, done, us_coarse / done, us_full / done, cap, (unsigned long long) calls, (unsigned long long) widens,
                    calls ? (double) cands / (double) calls : 0.0);
        common_sampler_free(coarse);
        common_sampler_free(full);
        llama_batch_free(batch);
    };

    run_case("plain", base, false, "");

    // a reasoning budget that FORCES the end of a think block mid-generation
    {
        common_params_sampling sp = base;
        sp.reasoning_budget_start  = common_tokenize(vocab, "<think>", false, true);
        sp.reasoning_budget_end    = { common_tokenize(vocab, "</think>", false, true) };
        sp.reasoning_budget_forced = common_tokenize(vocab, "\n</think>", false, true);
        sp.reasoning_budget_tokens = 40;
        run_case("reasoning budget", sp, false, "<think>\n");
    }

    // a lazy tool grammar (inactive until its trigger word appears)
    {
        common_params_sampling sp = base;
        sp.grammar = common_grammar(COMMON_GRAMMAR_TYPE_USER, "root ::= \"<tool_call>\" [a-z ]+ \"</tool_call>\"");
        sp.grammar_lazy = true;
        sp.grammar_triggers.push_back({ COMMON_GRAMMAR_TRIGGER_TYPE_WORD, "<tool_call>", LLAMA_TOKEN_NULL });
        run_case("lazy tool grammar", sp, false, "");
    }

    // logit biases (Codex on #122): ids outside the vocabulary are ignored on both paths (never read out of
    // bounds), two biases on one token sum on both paths, and a raised token joins the candidates
    {
        common_params_sampling sp = base;
        const llama_token the = common_tokenize(vocab, " the", false, false).at(0);
        const llama_token n_v = llama_vocab_n_tokens(vocab);
        sp.logit_bias = {
            { -1, 5.0f }, { n_v, 5.0f }, { n_v + 1000, -5.0f }, // outside the vocabulary
            { the, 3.0f }, { the, 4.0f },                        // duplicates: +7 on both paths
            { the + 1, -2.0f },
        };
        run_case("logit biases", sp, false, "");
    }

    // NaN logits (Codex on #122): the widening loop must end and the step must sample exactly as the full
    // array does, whether every logit is NaN, all but a few are, or a few are
    {
        const int n_v = llama_vocab_n_tokens(vocab);
        std::vector<float> logits(n_v);
        for (const int finite : { 0, 100, n_v - 1000 }) {
            for (int i = 0; i < n_v; ++i) {
                // distinct finite values (7919 is prime, so i*7919 mod finite permutes them): with ties, top-k's
                // order among equals is unspecified on both paths and "the same token" means nothing
                logits[i] = i < finite ? 10.0f * (float) (((int64_t) i * 7919) % finite) / (float) finite : NAN;
            }
            common_sampler_row row;
            row.logits  = logits.data();
            row.n_vocab = n_v;
            common_sampler * coarse = common_sampler_init(model, base);
            common_params_sampling full_params = base;
            full_params.n_probs = 1; // not ballpark-eligible: the full array
            common_sampler * full = common_sampler_init(model, full_params);
            for (int step = 0; step < 8; ++step) {
                const llama_token a = common_sampler_sample_row(coarse, row);
                const llama_token b = common_sampler_sample_row(full, row);
                if (a != b) {
                    std::fprintf(stderr, "FAILED: NaN logits (%d finite): ballpark %d, full %d\n", finite, a, b);
                    return 1;
                }
            }
            common_sampler_free(coarse);
            common_sampler_free(full);
            std::printf("%-18s %d finite of %d: the ballpark step ended and matched the full array\n", "NaN logits", finite, n_v);
        }
    }

    // speculative verify: the ballpark side samples through a clone every step
    run_case("clone each step", base, true, "");

    std::printf("test-sampler-coarse: ok\n");
    return 0;
}
